"""
quizzes/admin.py

Quiz, Question, Choice are editable.
QuizAttempt is READ-ONLY (generated by user activity).
"""
from django import forms
from django.contrib import admin

from .models import Choice, Question, Quiz, QuizAttempt


class ReadOnlyAdminMixin:
    def has_add_permission(self, request):
        return False

    def has_change_permission(self, request, obj=None):
        return False

    def has_delete_permission(self, request, obj=None):
        return request.user.is_superuser

    def has_view_permission(self, request, obj=None):
        return request.user.is_staff


class ChoiceFormSet(forms.BaseInlineFormSet):
    def clean(self):
        super().clean()
        filled = [
            f for f in self.forms
            if f.cleaned_data and not f.cleaned_data.get("DELETE", False)
        ]
        if len(filled) < 2:
            raise forms.ValidationError(
                "Each question must have at least 2 choices."
            )
        correct = sum(1 for f in filled if f.cleaned_data.get("is_correct", False))
        if correct != 1:
            raise forms.ValidationError(
                f"Exactly 1 choice must be marked correct (found {correct})."
            )


class ChoiceInline(admin.TabularInline):
    model = Choice
    formset = ChoiceFormSet
    extra = 4
    fields = ("text", "is_correct")


class QuestionInline(admin.StackedInline):
    model = Question
    extra = 1
    fields = ("order", "text")
    show_change_link = True


@admin.register(Quiz)
class QuizAdmin(admin.ModelAdmin):
    list_display = ("title", "node", "created_at", "updated_at")
    search_fields = ("title", "node__title", "node__roadmap__title")
    inlines = [QuestionInline]


@admin.register(Question)
class QuestionAdmin(admin.ModelAdmin):
    list_display = ("text", "quiz", "order")
    list_filter = ("quiz",)
    search_fields = ("text",)
    ordering = ("quiz", "order")
    inlines = [ChoiceInline]


@admin.register(Choice)
class ChoiceAdmin(admin.ModelAdmin):
    list_display = ("text", "question", "is_correct")
    list_filter = ("is_correct",)
    search_fields = ("text",)


@admin.register(QuizAttempt)
class QuizAttemptAdmin(ReadOnlyAdminMixin, admin.ModelAdmin):
    list_display = ("user", "quiz", "score_percent", "passed", "attempted_at")
    list_filter = ("passed",)
    search_fields = ("user__username", "quiz__node__title")
    date_hierarchy = "attempted_at"
